"""Check: manifests that conventionally use a lockfile have one committed."""

from pathlib import Path

from app.models.finding import FindingCategory, Severity
from app.scanner.checks.manifests import LOCKFILES, expects_lockfile, find_manifests
from app.scanner.fs import rel, safe_is_file
from app.scanner.types import CheckResult

CHECK_ID = "missing_lockfile"


def check_missing_lockfile(repo_root: Path) -> CheckResult | None:
    """
    Return a CheckResult for the first manifest lacking its lockfile, else None.

    Skipped (None) when there is no manifest, or only manifests without a lockfile
    convention (e.g. requirements.txt only).
    """
    root = repo_root.resolve()
    for manifest in find_manifests(root):
        if not expects_lockfile(manifest):
            continue
        candidates = LOCKFILES[manifest.name]
        if any(safe_is_file(root, manifest.parent / lock) for lock in candidates):
            continue
        return CheckResult(
            check_id=CHECK_ID,
            category=FindingCategory.dependencies,
            severity=Severity.low,
            title=f"No lockfile for {manifest.name}",
            recommendation=(
                f"Commit a lockfile next to {rel(root, manifest)} (one of: "
                f"{', '.join(candidates)}) generated by your package manager, so every "
                "install resolves exactly the same dependency versions."
            ),
            file_path=rel(root, manifest),
        )
    return None
